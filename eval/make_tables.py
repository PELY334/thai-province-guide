"""Turn the JSON results into eval/results/RESULTS.md (the tables quoted in the README).

    python eval/make_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "eval" / "results"


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}%"


def main() -> int:
    out = ["# Results", "", "Generated by `python eval/make_tables.py` from the JSON files in this folder.", ""]

    r = json.loads((RES / "retrieval.json").read_text())
    out += ["## Retrieval (test set, 34 answerable questions, k = 5)", "",
            "| embedding | chunk words | chunks | mode | hit@1 | recall@5 | MRR |",
            "|---|---:|---:|---|---:|---:|---:|"]
    for row in sorted(r["table"], key=lambda x: (x["chunk_words"], x["mode"])):
        emb = "–" if row["mode"] == "bm25" else row["embed_model"].split("/")[-1]
        out.append(f"| {emb} | {row['chunk_words']} | {row['n_chunks']} | {row['mode']} | "
                   f"{row['hit@1']:.3f} | {row['recall@5']:.3f} | {row['MRR']:.3f} |")
    b = r["best_min_score_dev"]
    out += ["", f"Floor sweep config: `{r['sweep_config']}` ({r['sweep_mode']}). Retrieval-only "
            f"best floor on dev = {b['min_score']} (balanced {b['balanced']:.3f}).", "",
            "| floor | test: answerable still retrievable | test: unanswerable rejected |",
            "|---:|---:|---:|"]
    for row in r["test_sweep"]:
        if row["min_score"] in (0.0, 0.6, 0.65, 0.68, 0.7, 0.72, 0.73, 0.75, 0.8):
            out.append(f"| {row['min_score']:.2f} | {pct(row['answerable_kept'])} | "
                       f"{pct(row['unanswerable_rejected'])} |")

    tune = RES / "min_score_tuning.json"
    if tune.exists():
        t = json.loads(tune.read_text())
        out += ["", f"## min_score tuned end-to-end on the dev set ({t['dev_n']} questions)", "",
                "| floor | dev overall | answered without an LLM call |", "|---:|---:|---:|"]
        for row in t["rows"]:
            mark = " **(chosen)**" if row["min_score"] == t["chosen"]["min_score"] else ""
            out.append(f"| {row['min_score']:.2f}{mark} | {pct(row['overall'])} | {pct(row['skipped_llm'])} |")

    s = json.loads((RES / "answers_summary.json").read_text())
    out += ["", "## Answers (test set: 34 answerable + 6 unanswerable)", "",
            "| system | accuracy (answerable) | single | reverse | multi+calc | correct abstain | "
            "false abstain | citation precision | overall | avg s | avg tool calls |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    order = ["closed_book", "rag@w250_nofloor", "rag_no_floor", "rag", "agent"]
    for name in order + [k for k in s if k not in order and not k.startswith("_")]:
        if name not in s:
            continue
        x = s[name]
        bt = x["by_type"]
        out.append(f"| {name} | {x['correct']} ({pct(x['accuracy'])}) | {bt.get('single', '–')} | "
                   f"{bt.get('reverse', '–')} | {bt.get('multi_calc', '–')} | {x['abstain_ok_n']} | "
                   f"{pct(x['false_abstain'])} | {pct(x['citation_prec'])} | {pct(x['overall'])} | "
                   f"{x['avg_seconds']:.1f} | {x['avg_tool_steps']:.1f} |")
    (RES / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
